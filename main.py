def max_dragon_strength(n: int) -> int:
     # Базовые случаи для 0 и 1 головы
    if n <= 1:
        return n
    
    # dp[i] будет хранить максимальную силу (произведение) для i голов
    dp = [0] * (n + 1)
    
    # Базовые значения для динамического программирования
    dp[0] = 1  # Нейтральный элемент для умножения
    dp[1] = 1  # 1 голова = сила 1
    
    # Заполняем таблицу ДП от 2 до N
    for i in range(2, n + 1):
        # Дракон может иметь от 1 до 7 голов (но не больше, чем осталось голов i)
        max_heads_per_dragon = min(7, i)
        
        for j in range(1, max_heads_per_dragon + 1):
            # j - количество голов у текущего дракона
            # dp[i - j] - максимальная сила, которую можно получить из оставшихся голов
            dp[i] = max(dp[i], j * dp[i - j])
            
    return dp[n]


