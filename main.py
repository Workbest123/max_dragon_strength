    test_cases = [
        (3, 3),    # 3 = 3 (или 1+1+1, но 3 > 1)
        (4, 4),    # 4 = 4 (или 2*2)
        (5, 6),    # 5 = 3 + 2 -> 3 * 2 = 6
        (7, 12),   # 7 = 3 + 4 -> 3 * 4 = 12
        (10, 36),  # 10 = 3 + 3 + 4 -> 3 * 3 * 4 = 36
        (15, 243)  # 15 = 3 + 3 + 3 + 3 + 3 -> 3^5 = 243
    ]
    
    print("Тестирование алгоритма:")
    for n, expected in test_cases:
        result = max_dragon_strength(n)
        status = "✅" if result == expected else "❌"
        print(f"{status} N={n:2d} | Ожидалось: {expected:3d} | Получено: {result:3d}")